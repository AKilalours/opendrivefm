#!/usr/bin/env python3
"""Table 1: per-class object-level results, in the DLWM per-class style.

A colour swatch per class, grouped headers under cmidrule, arrows in the
header, best value bold, the headline column shaded, and the classes where
observability LOSES printed rather than dropped.

  python3 scripts/paper/table1_perclass.py
  -> outputs/tables/table1_perclass.tex
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ART = os.path.join(ROOT, "outputs", "artifacts")
OUT = os.path.join(ROOT, "outputs", "tables")

# Occ3D's own class colours, so the swatches match any rendered figure.
SW = {"car": "3182BD", "truck": "D62728", "bus": "FFD700", "trailer": "8B4513",
      "construction vehicle": "40E0D0", "pedestrian": "FF0000",
      "motorcycle": "808000", "bicycle": "FFC0CB"}


def main():
    d = json.load(open(os.path.join(ART, "baselines_by_class.json")))
    o = json.load(open(os.path.join(ART, "baselines_object.json")))
    rows = sorted(d["classes"], key=lambda c: -c["n"])

    L = [r"% generated by scripts/paper/table1_perclass.py -- do not edit",
         r"\definecolor{odfmshade}{gray}{0.93}"]
    for k, v in SW.items():
        L.append(r"\definecolor{sw%s}{HTML}{%s}" % (k.replace(" ", ""), v))
    L += [
        r"\begin{table}[t]\centering\footnotesize",
        r"\setlength{\tabcolsep}{2.6pt}",
        r"\caption{\textbf{Per class, object level, sealed test split.} "
        r"\emph{missed} is the fraction of annotated objects the model never "
        r"predicts. AUROC columns rank that event. \textsc{oracle} counts "
        r"LiDAR returns inside the box and therefore sees a modality the "
        r"model does not; it is an upper reference, not a competitor. "
        r"Observability wins on the two largest classes and loses on "
        r"trailer and bicycle, and both losses are printed.}",
        r"\label{tab:perclass}",
        r"\begin{tabular}{llrrccc>{\columncolor{odfmshade}}c}",
        r"\toprule",
        r"& Class & $n$ & missed & \multicolumn{3}{c}{AUROC $\uparrow$} "
        r"& obs$-$conf \\",
        r"\cmidrule(lr){5-7}",
        r"& & & & conf. & obs. & \textsc{orac.} & $\Delta$ \\",
        r"\midrule",
    ]
    PRETTY = {"constr_veh": "construction vehicle"}
    for r in rows:
        c = PRETTY.get(r["cls"], r["cls"]); key = c.replace(" ", "")
        sw = r"\textcolor{sw%s}{$\blacksquare$}" % key if c in SW else ""
        best = max(r["obs"], r["msp"])
        f = lambda v: (r"\textbf{%.3f}" % v) if abs(v - best) < 1e-9 else "%.3f" % v
        dl = r["obs_minus_msp"]
        sig = dl[1] > 0 or dl[2] < 0
        dtxt = r"\textbf{%+.3f}" % dl[0] if sig else "%+.3f" % dl[0]
        L.append(f"{sw} & {c} & {r['n']:,} & {100*r['unplaced']:.1f}\\% & "
                 f"{f(r['msp'])} & {f(r['obs'])} & {r['oracle']:.3f} & "
                 f"{dtxt} \\\\")
    A = o["auroc"]; dl = o["contrasts"]["observability - MSP"]
    # A55: this cell used to carry a hand-typed 10.5%. It is the n-weighted
    # mean of the per-class miss rates and is 19.35%. A number nobody
    # computed is exactly the kind this project is not allowed to print.
    agg = (sum(r["n"] * r["unplaced"] for r in rows)
           / sum(r["n"] for r in rows))
    L += [
        r"\midrule",
        f"& \\textbf{{all dynamic}} & {o['objects']:,} & {100*agg:.1f}\\% & "
        f"{A['MSP (max conf in box)']:.3f} & "
        f"\\textbf{{{A['observability']:.3f}}} & "
        f"{A['LiDAR points in box (ORACLE)']:.3f} & "
        f"\\textbf{{{dl[0]:+.3f}}} \\\\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
    ]
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, "table1_perclass.tex"), "w").write("\n".join(L) + "\n")
    for r in rows:
        print(f"  {r['cls']:<22} n={r['n']:>6,}  conf {r['msp']:.3f}  "
              f"obs {r['obs']:.3f}  oracle {r['oracle']:.3f}  "
              f"d {r['obs_minus_msp'][0]:+.3f}")
    print("wrote outputs/tables/table1_perclass.tex")


if __name__ == "__main__":
    main()
